// @ts-check
/**
 * @module make-zone-table
 * Makes the zone table of custom places (SET-015, SET-018, MAP-002, DEC-029). With `--download` it
 * fetches IANA's `zone.tab` and `iso3166.tab` into data/ (the only network use, at development time,
 * with no user data). Without the flag it reads both files and writes data/zone-table.js: a frozen
 * `zones` list of `{ zone, countryCode, latitude, longitude }` sorted by zone name, the coordinates
 * of each zone's principal location in degrees, and a frozen `countryCodes` list. It does not read
 * the table at run time (`domain/zone-table.js` does).
 * Run it with `node scripts/make-zone-table.mjs --download`, then `node scripts/make-zone-table.mjs`.
 * Data: the tz database, public domain by the files' own headers (https://www.iana.org/time-zones).
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** The two files the `--download` step fetches (DEC-029). */
const sourceUrls = Object.freeze({
  "zone.tab": "https://data.iana.org/time-zones/tzdb/zone.tab",
  "iso3166.tab": "https://data.iana.org/time-zones/tzdb/iso3166.tab",
});

/**
 * Zones that a supported browser refuses (DEC-029); the four-browser test of SET-018 finds them.
 * America/Coyhaique: refused by Playwright's WebKit (found 2026-11-23).
 * @type {readonly string[]}
 */
export const skippedZones = Object.freeze(["America/Coyhaique"]);

/**
 * @typedef {object} ZoneRow
 * @property {string} zone IANA zone name.
 * @property {string} countryCode ISO 3166-1 alpha-2 code.
 * @property {number} latitude Degrees north, to two decimals.
 * @property {number} longitude Degrees east, to two decimals.
 */

/**
 * @param {number} value
 * @returns {number} The value rounded to two decimals.
 */
function twoDecimals(value) {
  return Math.round(value * 100) / 100;
}

/**
 * @param {string} sign `+` or `-`.
 * @param {string} digits Degrees, minutes and maybe seconds, two digits each after the degrees.
 * @param {number} degreeDigits 2 for a latitude, 3 for a longitude.
 * @returns {number} The angle in degrees, to two decimals.
 */
function angleOf(sign, digits, degreeDigits) {
  const degrees = Number(digits.slice(0, degreeDigits));
  const minutes = Number(digits.slice(degreeDigits, degreeDigits + 2));
  const seconds = Number(digits.slice(degreeDigits + 2) || "0");
  const value = degrees + minutes / 60 + seconds / 3600;
  return twoDecimals(sign === "-" ? -value : value);
}

/**
 * Reads the ISO 6709 coordinates of `zone.tab`'s second column.
 * @param {string} text `±DDMM±DDDMM` or `±DDMMSS±DDDMMSS`.
 * @returns {{ latitude: number, longitude: number }} In degrees, to two decimals.
 * @throws {RangeError} When the text has neither form.
 */
export function parseCoordinates(text) {
  const match = /^([+-])(\d{4}|\d{6})([+-])(\d{5}|\d{7})$/.exec(text);
  if (match === null) throw new RangeError(`Unreadable coordinates in zone.tab: ${text}`);
  const [, latSign, latDigits, lonSign, lonDigits] = match;
  return { latitude: angleOf(latSign, latDigits, 2), longitude: angleOf(lonSign, lonDigits, 3) };
}

/**
 * @param {string} text A tab-separated tz data file.
 * @returns {string[][]} The fields of each line that is neither empty nor a comment.
 */
function dataLines(text) {
  return text
    .split(/\r?\n/)
    .filter((line) => line.trim() !== "" && !line.startsWith("#"))
    .map((line) => line.split("\t"));
}

/**
 * @param {string} zoneTab The text of `zone.tab`.
 * @param {readonly string[]} skipped Zones to leave out.
 * @returns {ZoneRow[]} One row per zone, sorted by zone name.
 */
export function zoneRows(zoneTab, skipped) {
  return dataLines(zoneTab)
    .filter(([, , zone]) => !skipped.includes(zone))
    .map(([countryCode, coordinates, zone]) => ({
      zone,
      countryCode,
      ...parseCoordinates(coordinates),
    }))
    .sort((a, b) => (a.zone < b.zone ? -1 : 1));
}

/**
 * @param {string} isoTab The text of `iso3166.tab`.
 * @returns {string[]} The country codes, sorted.
 */
export function countryCodesOf(isoTab) {
  return dataLines(isoTab)
    .map(([code]) => code)
    .sort();
}

/**
 * @param {ZoneRow[]} rows
 * @param {string[]} codes
 * @returns {string} The text of data/zone-table.js.
 */
export function zoneTableSource(rows, codes) {
  const rowLines = rows.map(
    (row) =>
      `  { zone: ${JSON.stringify(row.zone)}, countryCode: "${row.countryCode}", ` +
      `latitude: ${row.latitude}, longitude: ${row.longitude} },`,
  );
  return [
    "// @ts-check",
    "/**",
    " * @module data/zone-table",
    " * The zone table of custom places (DEC-029), generated by scripts/make-zone-table.mjs from IANA's",
    " * zone.tab and iso3166.tab (public domain). Never edit it by hand: run the script again.",
    " * It holds data only; `domain/zone-table.js` looks it up.",
    " */",
    "",
    "/**",
    " * @typedef {object} ZoneRow One time zone of zone.tab.",
    " * @property {string} zone IANA zone name.",
    " * @property {string} countryCode ISO 3166-1 alpha-2 code of the zone's country or territory.",
    " * @property {number} latitude Degrees north of the zone's principal location.",
    " * @property {number} longitude Degrees east of the zone's principal location.",
    " */",
    "",
    "/** @type {readonly ZoneRow[]} */",
    "export const zones = Object.freeze([",
    ...rowLines,
    "]);",
    "",
    "/** @type {readonly string[]} The ISO 3166-1 alpha-2 codes of iso3166.tab. */",
    `export const countryCodes = Object.freeze(${JSON.stringify(codes)});`,
    "",
  ].join("\n");
}

/**
 * Fetches the two tz data files into data/.
 * @param {string} dataDir
 * @returns {Promise<void>}
 */
async function download(dataDir) {
  for (const [name, url] of Object.entries(sourceUrls)) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Download of ${url} failed: ${response.status}`);
    await writeFile(path.join(dataDir, name), Buffer.from(await response.arrayBuffer()));
  }
}

/**
 * Runs the download or the generation for the repository when this file is started from the
 * command line.
 */
async function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const dataDir = path.join(root, "data");
  if (process.argv.includes("--download")) {
    await download(dataDir);
    return;
  }
  const zoneTab = await readFile(path.join(dataDir, "zone.tab"), "utf8");
  const isoTab = await readFile(path.join(dataDir, "iso3166.tab"), "utf8");
  const source = zoneTableSource(zoneRows(zoneTab, skippedZones), countryCodesOf(isoTab));
  await writeFile(path.join(dataDir, "zone-table.js"), source);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
